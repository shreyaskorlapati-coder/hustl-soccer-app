/**
 * useGoogleAuth
 *
 * Shared hook for Google OAuth sign-in (mobile id_token flow).
 * Works with expo-auth-session's useIdTokenAuthRequest under the hood.
 *
 * Usage:
 *   const { promptGoogleSignIn, isConfigured } = useGoogleAuth({
 *     onSuccess: async (idToken) => { ... },
 *     onError:  (message) => { ... },
 *     onCancel: () => { ... },
 *   });
 *
 * Prerequisites (Google Cloud Console):
 *   1. Create an OAuth Web Application client — add these redirect URIs:
 *        https://auth.expo.io/@<expo-username>/hustl     (Expo Go)
 *        hustl://                                         (native builds)
 *   2. Create an iOS OAuth client (bundle ID: app.hustl)
 *   3. Create an Android OAuth client (package: com.hustl)
 *   4. Fill in the three EXPO_PUBLIC_GOOGLE_*_CLIENT_ID vars in frontend/.env
 */

import * as Google from "expo-auth-session/providers/google";
import * as WebBrowser from "expo-web-browser";
import { makeRedirectUri } from "expo-auth-session";
import { useCallback, useEffect, useRef } from "react";

// Register the custom scheme so the OS can route the OAuth redirect back to the app.
WebBrowser.maybeCompleteAuthSession();

const WEB_CLIENT_ID = process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID ?? "";
const IOS_CLIENT_ID = process.env.EXPO_PUBLIC_GOOGLE_IOS_CLIENT_ID ?? "";
const ANDROID_CLIENT_ID = process.env.EXPO_PUBLIC_GOOGLE_ANDROID_CLIENT_ID ?? "";

// Use the app's registered custom scheme so Google receives a URI it accepts.
// exp:// URIs (generated by Expo Go) are rejected by Google OAuth.
// This URI must also be listed in Google Cloud Console → Authorized redirect URIs.
const REDIRECT_URI = makeRedirectUri({ scheme: "hustl", path: "/" });

/** True when at least the web client ID is configured. */
export const GOOGLE_CONFIGURED = !!WEB_CLIENT_ID;

export interface UseGoogleAuthOptions {
  /**
   * Called with the raw Google id_token once the user approves the consent
   * screen.  Perform your backend call here.
   */
  onSuccess: (idToken: string) => Promise<void>;
  /** Called when Google returns an error or the id_token is missing. */
  onError?: (message: string) => void;
  /** Called when the user dismisses or cancels the browser. */
  onCancel?: () => void;
}

export interface UseGoogleAuthReturn {
  /**
   * Open the Google consent screen.
   * Returns false immediately (without opening anything) when not configured.
   */
  promptGoogleSignIn: () => Promise<boolean>;
  /** Whether the Google client IDs are present in the env. */
  isConfigured: boolean;
}

export function useGoogleAuth({
  onSuccess,
  onError,
  onCancel,
}: UseGoogleAuthOptions): UseGoogleAuthReturn {
  // Keep callback refs stable so the effect below doesn't re-subscribe on every render.
  const onSuccessRef = useRef(onSuccess);
  const onErrorRef = useRef(onError);
  const onCancelRef = useRef(onCancel);
  onSuccessRef.current = onSuccess;
  onErrorRef.current = onError;
  onCancelRef.current = onCancel;

  // expo-auth-session requires hooks to be called unconditionally.
  // When not configured we pass a dummy client ID; the guard in promptGoogleSignIn
  // ensures promptAsync() is never called in that state.
  const [, response, promptAsync] = Google.useIdTokenAuthRequest({
    clientId: WEB_CLIENT_ID || "__not_configured__",
    iosClientId: IOS_CLIENT_ID || undefined,
    androidClientId: ANDROID_CLIENT_ID || undefined,
    redirectUri: REDIRECT_URI,
  });

  useEffect(() => {
    if (!response) return;

    switch (response.type) {
      case "success": {
        const idToken = response.params?.id_token;
        if (idToken) {
          onSuccessRef.current(idToken);
        } else {
          onErrorRef.current?.("Google did not return an identity token. Please try again.");
        }
        break;
      }
      case "error":
        onErrorRef.current?.(
          response.error?.message ?? "Google sign-in encountered an error. Please try again."
        );
        break;
      case "cancel":
      case "dismiss":
        onCancelRef.current?.();
        break;
      default:
        break;
    }
  }, [response]);

  const promptGoogleSignIn = useCallback(async (): Promise<boolean> => {
    if (!GOOGLE_CONFIGURED) return false;
    await promptAsync();
    return true;
  }, [promptAsync]);

  return { promptGoogleSignIn, isConfigured: GOOGLE_CONFIGURED };
}
